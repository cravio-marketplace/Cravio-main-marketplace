-- Cravio Admin Portal foundation. Apply manually after review; not executed by deployment.
CREATE TABLE IF NOT EXISTS public.admin_profiles (
 user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
 full_name text NOT NULL DEFAULT '', avatar_url text,
 role text NOT NULL CHECK(role IN ('super_admin','support')),
 status text NOT NULL DEFAULT 'active' CHECK(status IN ('active','suspended')),
 created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now(),last_login_at timestamptz
);
CREATE TABLE IF NOT EXISTS public.admin_audit_logs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
 actor_role text NOT NULL CHECK(actor_role IN ('super_admin','support')),
 action text NOT NULL,resource_type text NOT NULL,resource_id text,
 old_value jsonb,new_value jsonb,reason text,request_id text,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS admin_audit_logs_created_idx ON public.admin_audit_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS admin_audit_logs_actor_idx ON public.admin_audit_logs(actor_user_id,created_at DESC);
CREATE TABLE IF NOT EXISTS public.admin_disputes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE RESTRICT,
 status text NOT NULL DEFAULT 'open' CHECK(status IN ('open','resolved')),
 resolution text CHECK(resolution IN ('refund','no_action')),notes text NOT NULL DEFAULT '',
 opened_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,resolved_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
 resolved_at timestamptz,created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS admin_disputes_status_created_idx ON public.admin_disputes(status,created_at DESC);
CREATE TABLE IF NOT EXISTS public.platform_settings (
 key text PRIMARY KEY,value jsonb NOT NULL,updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.customer_account_controls (
 user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,is_blocked boolean NOT NULL DEFAULT false,
 reason text,updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.vendors ADD COLUMN IF NOT EXISTS admin_suspended boolean NOT NULL DEFAULT false;
ALTER TABLE public.vendors ADD COLUMN IF NOT EXISTS commission_rate_bps_override integer CHECK(commission_rate_bps_override IS NULL OR commission_rate_bps_override BETWEEN 0 AND 10000);
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS admin_dispute_flag boolean NOT NULL DEFAULT false;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS admin_refund_reason text;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS admin_refunded_at timestamptz;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS admin_refunded_by uuid REFERENCES auth.users(id) ON DELETE SET NULL;
CREATE OR REPLACE FUNCTION public.cravio_admin_role() RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$ SELECT role FROM public.admin_profiles WHERE user_id=auth.uid() AND status='active' LIMIT 1 $$;
CREATE OR REPLACE FUNCTION public.cravio_is_admin() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$ SELECT public.cravio_admin_role() IN ('super_admin','support') $$;
CREATE OR REPLACE FUNCTION public.cravio_is_super_admin() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$ SELECT public.cravio_admin_role()='super_admin' $$;
REVOKE ALL ON FUNCTION public.cravio_admin_role() FROM PUBLIC; REVOKE ALL ON FUNCTION public.cravio_is_admin() FROM PUBLIC; REVOKE ALL ON FUNCTION public.cravio_is_super_admin() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.cravio_admin_role(),public.cravio_is_admin(),public.cravio_is_super_admin() TO authenticated,service_role;
ALTER TABLE public.admin_profiles ENABLE ROW LEVEL SECURITY;ALTER TABLE public.admin_audit_logs ENABLE ROW LEVEL SECURITY;ALTER TABLE public.admin_disputes ENABLE ROW LEVEL SECURITY;ALTER TABLE public.platform_settings ENABLE ROW LEVEL SECURITY;ALTER TABLE public.customer_account_controls ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS admin_profiles_read ON public.admin_profiles;
CREATE POLICY admin_profiles_read ON public.admin_profiles FOR SELECT TO authenticated USING(user_id=auth.uid() OR public.cravio_is_admin());
DROP POLICY IF EXISTS admin_profiles_super_manage ON public.admin_profiles;
CREATE POLICY admin_profiles_super_manage ON public.admin_profiles FOR ALL TO authenticated USING(public.cravio_is_super_admin()) WITH CHECK(public.cravio_is_super_admin());
DROP POLICY IF EXISTS admin_audit_read ON public.admin_audit_logs;
CREATE POLICY admin_audit_read ON public.admin_audit_logs FOR SELECT TO authenticated USING(public.cravio_is_admin());
DROP POLICY IF EXISTS admin_disputes_access ON public.admin_disputes;
CREATE POLICY admin_disputes_access ON public.admin_disputes FOR ALL TO authenticated USING(public.cravio_is_admin()) WITH CHECK(public.cravio_is_admin());
DROP POLICY IF EXISTS platform_settings_super_access ON public.platform_settings;
CREATE POLICY platform_settings_super_access ON public.platform_settings FOR ALL TO authenticated USING(public.cravio_is_super_admin()) WITH CHECK(public.cravio_is_super_admin());
DROP POLICY IF EXISTS customer_controls_admin_access ON public.customer_account_controls;
CREATE POLICY customer_controls_admin_access ON public.customer_account_controls FOR ALL TO authenticated USING(public.cravio_is_admin()) WITH CHECK(public.cravio_is_admin());
GRANT SELECT ON public.admin_profiles,public.admin_audit_logs,public.admin_disputes,public.platform_settings,public.customer_account_controls TO authenticated;
GRANT ALL ON public.admin_profiles,public.admin_audit_logs,public.admin_disputes,public.platform_settings,public.customer_account_controls TO service_role;

